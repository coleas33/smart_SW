/// <summary>
/// Decision 21A (feature 004, 2026-09-25, the owner), T165. <see cref="ReadOnlyGuard"/> refused
/// feature creation only through three prefixes, so <c>FeatureFillet3</c>, <c>FeatureRevolve2</c>,
/// <c>InsertMirrorFeature2</c>, <c>InsertPart3</c>, <c>MirrorPart2</c>, the sheet-metal and pattern
/// creators and the like passed a read-only gate as bare names.
///
/// <b>The "Decision 21A" tables of <c>004-resilient-remodeler/contracts/guard-allowlist.md</c> are the
/// membership, and this class reads them</b>, as <see cref="DrawingFamilyDenylistTests"/> reads feature
/// 011's. They are generated by <c>extractor/tools/list-creation-members.ps1</c> from the interop and
/// never typed; <see cref="CreationFamilyCompletenessTests"/> reflects the same interop at test time to
/// prove them complete. Only <see cref="RemodelProbeGuard"/> exempts any member, for the throwaway part
/// it builds (<see cref="ThrowawayPartExemptionTests"/>).
/// </summary>
public class CreationFamilyDenylistTests
{
    internal const string AllowlistFileName = "guard-allowlist.md";

    internal const string Document = "specs/004-resilient-remodeler/contracts/guard-allowlist.md (decision 21A)";

    /// <summary>The header of the generated table of creation-grammar matches.</summary>
    internal const string TableHeader = "| Members refused (decision 21A) | Interface; already denied |";

    /// <summary>The header of the generated table of named creators the grammar does not reach.</summary>
    internal const string NamedHeader = "| Named creators refused (decision 21A) | Interface; what it builds |";

    /// <summary>The header of the generated table of grammar matches left allowed.</summary>
    internal const string ExclusionHeader = "| Not denied (decision 21A) | Why |";

    /// <summary>
    /// The reads the grammar reaches, left allowed by rule 3 of the contract. Written here a second
    /// time, beside the generator's copy, on purpose: this is the check of the generated "Not denied"
    /// table, in both directions.
    /// </summary>
    internal static readonly string[] ReadsTheGrammarReaches =
    {
        "FeatureById", "IFeatureById",
        "FeatureByName", "IFeatureByName",
        "FeatureByPositionReverse", "IFeatureByPositionReverse",
        "FeatureFolderLocation",
        "CreateMassProperty", "CreateMassProperty2",
        "CreateMeasure",
    };

    /// <summary>The grammar table, parsed: one row per interface.</summary>
    public static readonly IReadOnlyList<(string Family, string[] Members)> Table = DenylistTable.Parse(
        AllowlistFileName, Document, TableHeader, minimumRows: 4);

    /// <summary>The named-creator table, parsed: one row per interface and what it builds.</summary>
    public static readonly IReadOnlyList<(string Family, string[] Members)> Named = DenylistTable.Parse(
        AllowlistFileName, Document + " named creators", NamedHeader, minimumRows: 5);

    /// <summary>The names the grammar matched and the section leaves allowed.</summary>
    public static readonly IReadOnlyList<(string Family, string[] Members)> Exclusions = DenylistTable.Parse(
        AllowlistFileName, Document + " exclusions", ExclusionHeader, minimumRows: 5);

    /// <summary>Every (interface, member) pair the two denial tables name.</summary>
    internal static IEnumerable<(string Interface, string Member)> Rows() =>
        Table.Concat(Named).SelectMany(row => row.Members.Select(
            member => (DrawingFamilyDenylistTests.InterfaceOf(row), member)));

    /// <summary>The distinct bare names the two tables deny: the expected set, derived.</summary>
    public static IReadOnlyCollection<string> ExpectedMembers =>
        new HashSet<string>(Rows().Select(row => row.Member), StringComparer.OrdinalIgnoreCase);

    /// <summary>The distinct bare names the exclusion table leaves allowed.</summary>
    public static IReadOnlyCollection<string> ExcludedMembers =>
        new HashSet<string>(Exclusions.SelectMany(row => row.Members), StringComparer.OrdinalIgnoreCase);

    public static IEnumerable<object[]> EveryMember() =>
        ExpectedMembers.OrderBy(member => member, StringComparer.Ordinal)
            .Select(member => new object[] { member });

    public static IEnumerable<object[]> EveryQualifiedMember() =>
        Rows().Select(row => row.Interface + "." + row.Member)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(key => key, StringComparer.Ordinal)
            .Select(key => new object[] { key });

    public static IEnumerable<object[]> EveryExcludedMember() =>
        ExcludedMembers.OrderBy(member => member, StringComparer.Ordinal)
            .Select(member => new object[] { member });

