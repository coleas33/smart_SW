"""T053's first acceptance line: eleven findings, one per US1 check except the transparency
one, which is unresolved while `TRANSPARENCY_POLARITY` is unsettled (SC-014). The four
drawing ids join this map with T070, once their evaluators exist."""


def graded(case_name: str) -> dict[str, Any]:
    """One golden case, run the way `test_golden.py` runs it."""
    directory = FIXTURES_DIR / case_name
    case = json.loads((directory / "case.json").read_text(encoding="utf-8"))
    function = resolve_callable(case["callable"])
    return function(load_package(directory).package, **case.get("kwargs", {}))


def package_of(case_name: str) -> EvidencePackage:
    return load_package(FIXTURES_DIR / case_name).package


def findings_by_check(result: dict[str, Any]) -> dict[str, list[dict[str, Any]]]:
    by_check: dict[str, list[dict[str, Any]]] = {}
    for finding in result["findings"]:
        by_check.setdefault(finding["check"], []).append(finding)
    return by_check


def buckets_of(result: dict[str, Any], check: str) -> dict[str, list[str]]:
    """Which documents `check` landed in which bucket, off the coverage rows."""
    landed: dict[str, list[str]] = {}
    for row in result["coverage"]:
        if row["check"] != check:
            continue
        landed.setdefault(row["bucket"], []).extend(row["scope"]["document_ids"])
    return landed


def unresolved_checks(result: dict[str, Any]) -> set[str]:
    return {
        row["check"]
        for row in result["coverage"]
        if row["bucket"] == "unresolved" and row["check"] in RULES
    }


def document_of(finding: dict[str, Any]) -> str:
    return str(finding["provenance"][0]["document_id"])


def sub_assemblies(package: EvidencePackage) -> list[str]:
    """Every assembly below the top one, which is what difference h's rows name.

    The top assembly is the root document when a model was opened, and the one the root
    drawing's views reference when a drawing was: `design.root_assembly_document_id` holds
    the **drawing's** id for a drawing root, which is the feature 003 misnomer
    `contracts/ir-additions.md` section 7 keeps deliberately.
    """
    tops = {
        package.design.root_assembly_document_id,
        *(
            view.referenced_document_id
            for record in package.drawing_records
            for sheet in record.sheets
            for view in sheet.views
            if view.referenced_document_id is not None
        ),
    }
    return [
        row.document_id
        for row in package.documents
        if row.kind == "assembly" and row.document_id not in tops
    ]


def document_id_for(package: EvidencePackage, file_name: str) -> str:
    return next(row.document_id for row in package.documents if row.file_name == file_name)


def reached_only_through_unresolved_instances(package: EvidencePackage) -> set[str]:
    """Documents every instance of which is suppressed, lightweight or unloaded (FR-005)."""
    states: dict[str, set[str]] = {}
    for row in package.components:
        states.setdefault(row.document_id, set()).add(row.suppression)
    return {
        document_id
        for document_id, seen in states.items()
        if seen and "resolved" not in seen
    }


def full_paths_of(package: EvidencePackage, component_ids: list[str]) -> list[str]:
    """The occurrence path of each instance, in the order the finding named them.

    The finding shape T047 pins is id-only: `component_ids` and the `inputs` lines carry
    ids and the scope document, and neither they nor the `subjects` rows beside them carry
    `full_path`. So T056's "every path" is named *through* those ids, and this is what
    resolves them - a named id that no instance carries would raise here.
    """
    by_id = {row.id: row.full_path for row in package.components}
    return [by_id[component_id] for component_id in component_ids]


def shared_document_id(package: EvidencePackage) -> str:
    """The one assembly document two different parent instances both reach."""
    parents: dict[str, set[str | None]] = {}
    for row in package.components:
        parents.setdefault(row.document_id, set()).add(row.parent_id)
    assemblies = {row.document_id for row in package.documents if row.kind == "assembly"}
    shared = [
        document_id
        for document_id, seen in parents.items()
        if document_id in assemblies and len(seen) > 1
    ]
    assert len(shared) == 1, shared
    return shared[0]


