# --- T053: standards-seeded ---------------------------------------------------------------


class TestSeeded:
    """One violation, in one document, of each of the sixteen checks (SC-001, SC-006)."""

    def test_each_us1_check_but_the_transparency_one_produces_exactly_one_finding(
        self, seeded: dict[str, Any]
    ) -> None:
        counts = {check: len(rows) for check, rows in findings_by_check(seeded).items()}

        assert counts == SEEDED_FINDINGS

    def test_eleven_findings_and_no_twelfth(self, seeded: dict[str, Any]) -> None:
        assert len(seeded["findings"]) == 11

    def test_the_transparency_check_is_one_unresolved_row_and_no_finding(
        self, seeded: dict[str, Any]
    ) -> None:
        landed = buckets_of(seeded, TRANSPARENCY)

        assert set(landed) - {"out_of_scope"} == {"unresolved"}
        assert len(landed["unresolved"]) == 1

    def test_no_seventeenth_check_result(self, seeded: dict[str, Any]) -> None:
        rows = [row["check"] for row in seeded["checks"]]

        assert rows == list(RULES)
        assert STANDARDS_FAMILY.summary_check not in rows

    def test_the_summary_item_is_present_and_is_not_counted_as_a_check(
        self, seeded: dict[str, Any]
    ) -> None:
        summaries = [
            row for row in seeded["coverage"] if row["check"] == STANDARDS_FAMILY.summary_check
        ]

        assert len(summaries) == 1
        assert STANDARDS_FAMILY.summary_check not in RULES

    def test_every_finding_carries_the_status_its_check_severity_maps_to(
        self, seeded: dict[str, Any]
    ) -> None:
        for finding in seeded["findings"]:
            rule = RULES[finding["check"]]
            expected = STANDARDS_FAMILY.status_by_severity[str(rule.severity)][0]
            assert finding["status"] == expected, finding["check"]

    def test_the_failing_part_is_reached_through_twenty_instances(
        self, seeded: dict[str, Any]
    ) -> None:
        """SC-006's first half: one finding per document, naming every instance."""
        part_findings = [
            finding
            for finding in seeded["findings"]
            if finding["check"].startswith("standards.part.")
        ]

        assert len(part_findings) == 4
        for finding in part_findings:
            assert len(finding["component_ids"]) == 20, finding["check"]

    def test_the_seeded_drawing_carries_six_overridden_dimensions(self) -> None:
        """SC-006's second half, seeded now and graded by T070."""
        package = package_of("standards-seeded")
        overridden = [
            dimension
            for record in package.drawing_records
            for sheet in record.sheets
            for view in sheet.views
            for dimension in view.display_dimensions
            if dimension.is_overridden
        ]

        assert len(overridden) == 6
        assert len({dimension.view_id for dimension in overridden}) == 1

    def test_the_package_holds_exactly_one_assembly_document_and_one_drawing(self) -> None:
        """SC-001: a second assembly would add difference-h rows the counts exclude."""
        package = package_of("standards-seeded")
        assemblies = [row for row in package.documents if row.kind == "assembly"]
        drawings = [row for row in package.documents if row.kind == "drawing"]

        assert len(assemblies) == 1
        assert len(drawings) == 1

    def test_the_drawing_views_reference_that_same_root_assembly(self) -> None:
        package = package_of("standards-seeded")
        assembly = next(row.document_id for row in package.documents if row.kind == "assembly")
        referenced = {
            view.referenced_document_id
            for record in package.drawing_records
            for sheet in record.sheets
            for view in sheet.views
            if view.referenced_document_id is not None
        }

        assert referenced == {assembly}

    def test_two_violations_are_seeded_at_depth(self, seeded: dict[str, Any]) -> None:
        """Difference z: a defect inside a folder or a derived feature is still a subject."""
        package = package_of("standards-seeded")
        nested = {row.id for row in package.features if row.folder_id is not None}
        by_check = findings_by_check(seeded)

        for check in ("standards.part.sketches_fully_defined", "standards.part.rebuild_errors"):
            named = {entry.split()[1] for entry in by_check[check][0]["inputs"]}
            assert named & nested, check

    def test_the_four_drawing_checks_are_unresolved_over_the_drawing_and_unavailable(
        self, seeded: dict[str, Any]
    ) -> None:
        package = package_of("standards-seeded")
        drawing_id = next(row.document_id for row in package.documents if row.kind == "drawing")
        for check in DRAWING_CHECKS:
            landed = buckets_of(seeded, check)
            assert landed.get("unresolved") == [drawing_id], check

        assert [row["check"] for row in seeded["unavailable_checks"]] == list(DRAWING_CHECKS)

    def test_the_verdict_is_not_ready_and_carries_the_unresolved_ids(
        self, seeded: dict[str, Any]
    ) -> None:
        verdict = seeded["verdict"]

        assert verdict["state"] == "not_ready"
        assert verdict["counts"]["error"] == 11
        assert TRANSPARENCY in verdict["unresolved_check_ids"]


# --- T054: standards-compliant and standards-compliant-flat -------------------------------


class TestCompliant:
    """SC-002's model half: zero findings, and what `ready` costs."""

    def test_the_multi_level_fixture_produces_zero_findings(
        self, compliant: dict[str, Any]
    ) -> None:
        assert compliant["findings"] == []

    def test_the_multi_level_fixture_carries_parts_sub_assemblies_and_a_drawing(self) -> None:
        package = package_of("standards-compliant")
        kinds = {row.kind for row in package.documents}

        assert kinds == {"part", "assembly", "drawing"}
        assert sub_assemblies(package)

    @pytest.mark.parametrize(
        ("case", "known_gaps"),
        [
            ("compliant", frozenset({MATE_REFERENCES, FULLY_MATED, TRANSPARENCY})),
            ("flat", frozenset({TRANSPARENCY})),
        ],
    )
    def test_every_us1_check_is_checked_or_skipped_with_a_stated_reason(
        self,
        case: str,
        known_gaps: frozenset[str],
        request: pytest.FixtureRequest,
    ) -> None:
        """T054's acceptance line, asked of **both** compliant fixtures.

        `standards-compliant-flat` is the one the Phase 3 Independent Test names - the
        single-level fixture of spec.md:21 - so the assertion has to be made there too: a
        check that emitted no coverage row at all for that package would be the silent
        skip the hard rules forbid, and `findings == []` cannot see it. The flat fixture
        has no sub-assembly, so the two difference-h gaps do not arise there and only the
        unsettled transparency polarity is left unresolved.
        """
        result: dict[str, Any] = request.getfixturevalue(case)
        for check in US1_CHECKS:
            landed = buckets_of(result, check)
            assert landed, check
            graded_buckets = set(landed) - {"out_of_scope"}
            if check in known_gaps:
                assert "unresolved" in graded_buckets, check
            else:
                assert graded_buckets <= {"checked", "skipped"}, check
        for row in result["coverage"]:
            assert row["reason"], row["check"]

    def test_the_two_known_gaps_name_each_sub_assembly(self, compliant: dict[str, Any]) -> None:
        subs = sub_assemblies(package_of("standards-compliant"))

        assert subs
        assert buckets_of(compliant, MATE_REFERENCES)["unresolved"] == subs
        assert buckets_of(compliant, FULLY_MATED)["unresolved"] == subs

    def test_the_unresolved_ids_are_the_two_gaps_the_polarity_and_the_unbound_drawings(
        self, compliant: dict[str, Any]
    ) -> None:
        """T069a replaces the drawing half of this set once the evaluators exist."""
        expected = {MATE_REFERENCES, FULLY_MATED, TRANSPARENCY, *DRAWING_CHECKS}

        assert unresolved_checks(compliant) == expected
        assert set(compliant["verdict"]["unresolved_check_ids"]) == expected

    def test_the_multi_level_verdict_is_ready_coverage_incomplete(
        self, compliant: dict[str, Any]
    ) -> None:
        assert compliant["verdict"]["state"] == "ready_coverage_incomplete"
        assert compliant["verdict"]["counts"]["error"] == 0

    def test_the_flat_fixture_produces_zero_findings(self, flat: dict[str, Any]) -> None:
        assert flat["findings"] == []

    def test_the_flat_fixture_has_no_sub_assembly_and_one_drawing(self) -> None:
        package = package_of("standards-compliant-flat")
        drawings = [row for row in package.documents if row.kind == "drawing"]

        assert sub_assemblies(package) == []
        assert len(drawings) == 1

    def test_the_flat_fixture_is_unresolved_only_where_this_build_cannot_answer(
        self, flat: dict[str, Any]
    ) -> None:
        """SC-014 removes the polarity row and T066 the four drawing ones; then `ready`."""
        assert unresolved_checks(flat) == {TRANSPARENCY, *DRAWING_CHECKS}

    def test_the_flat_headline_carries_no_no_drawing_note(self, flat: dict[str, Any]) -> None:
        assert "no drawing graded" not in flat["verdict"]["notes"]

    def test_every_compliant_drawing_sheet_records_a_sheet_format_view(self) -> None:
        """Without a type-1 view per sheet `no_itar_statement` can never reach `ready`."""
        for case in ("standards-compliant", "standards-compliant-flat"):
            for record in package_of(case).drawing_records:
                for sheet in record.sheets:
                    assert any(view.view_type_raw == 1 for view in sheet.views), sheet.name


