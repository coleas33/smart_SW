class TestUnknown:
    """SC-003's model half: unknown stays unknown, and never becomes a pass."""

    def test_the_fixture_is_otherwise_compliant(self, unknown: dict[str, Any]) -> None:
        assert unknown["verdict"]["counts"]["error"] == 0
        assert unknown["findings"] == []

    def test_the_verdict_is_ready_coverage_incomplete_naming_the_unresolved_ids(
        self, unknown: dict[str, Any]
    ) -> None:
        assert unknown["verdict"]["state"] == "ready_coverage_incomplete"
        assert unresolved_checks(unknown) == UNKNOWN_UNRESOLVED
        assert set(unknown["verdict"]["unresolved_check_ids"]) == UNKNOWN_UNRESOLVED

    def test_the_suppressed_and_lightweight_components_are_skipped_with_their_state(
        self, unknown: dict[str, Any]
    ) -> None:
        for check in (
            "standards.assembly.one_fixed",
            "standards.assembly.fully_mated",
            "standards.assembly.not_hidden",
        ):
            reasons = " ".join(
                row["reason"]
                for row in unknown["coverage"]
                if row["check"] == check and row["bucket"] == "skipped"
            )
            assert "suppressed" in reasons, check
            assert "lightweight" in reasons, check

    def test_the_unreadable_sketch_status_is_unresolved_and_that_part_is_not_checked(
        self, unknown: dict[str, Any]
    ) -> None:
        check = "standards.part.sketches_fully_defined"
